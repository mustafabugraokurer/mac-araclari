    @objc.python_method
    def _bolge(self, r, ad, acc, sec, buyuk):
        aktif = self.hover == ad
        path = NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(r, 12, 12)
        if aktif:
            acc.colorWithAlphaComponent_(0.16).set()
            path.fill()
        path.setLineWidth_(2 if (ad == "kes" or aktif) else 1.5)
        path.setLineDash_count_phase_([6, 4], 2, 0)
        (acc if (ad == "kes" or aktif) else NSColor.tertiaryLabelColor()).set()
        path.stroke()
        if ad == "kes":
            baslik = t("Bırak: taşı")
            alt = t("Dosyalar kesilir, bırakana kadar burada bekler") if buyuk else t("kes")
            renk = acc
        else:
            baslik = t("Kopyala")
            alt = t("⌥ basılı tutarak da bırakabilirsin")
            renk = NSColor.labelColor()
        if buyuk:
            ic = sembol("scissors", 28)
            if ic:
                ic.drawInRect_fromRect_operation_fraction_respectFlipped_hints_(
                    NSMakeRect(r.origin.x + r.size.width / 2 - 14, r.origin.y + 26, 28, 28),
                    NSMakeRect(0, 0, 0, 0), 2, 1.0, True, None)
            yazi(baslik, 15, 0.6, renk, hiza=1).drawInRect_(
                NSMakeRect(r.origin.x, r.origin.y + 64, r.size.width, 20))
            yazi(alt, 12, 0, sec, kes=False, hiza=1).drawInRect_(
                NSMakeRect(r.origin.x + 16, r.origin.y + 90, r.size.width - 32, 36))
        else:
            yazi(baslik, 13, 0.4, renk).drawInRect_(
                NSMakeRect(r.origin.x + 14, r.origin.y + r.size.height / 2 - 9,
                           100, 18))
            if r.size.height >= 50:
                yazi(alt, 11, 0, sec).drawInRect_(
                    NSMakeRect(r.origin.x + 14, r.origin.y + r.size.height / 2 + 9,
                               r.size.width - 28, 15))

    # ---- bırakma hedefi (dosyalar taşıma alanına giriyor)
    @objc.python_method
    def _mod(self, sender):
        if sender.draggingSource() is self:
            return None
        pt = self.convertPoint_fromView_(sender.draggingLocation(), None)
        L = self.yerlesim()
        k = L["kopya"]
        alt_basili = bool(NSEvent.modifierFlags() & MOD_ALT)
        icinde = (k.origin.x <= pt.x <= k.origin.x + k.size.width and
                  k.origin.y <= pt.y <= k.origin.y + k.size.height)
        return "kopya" if (alt_basili or icinde) else "kes"

    def draggingEntered_(self, sender):
        return self.draggingUpdated_(sender)

    def draggingUpdated_(self, sender):
        m = self._mod(sender)
        if m != self.hover:
            self.hover = m
            self.setNeedsDisplay_(True)
        if self.app:
            self.app.shelf_touched()
        return 0 if m is None else (OP_COPY if m == "kopya" else OP_MOVE)

    def draggingExited_(self, sender):
        self.hover = None
        self.setNeedsDisplay_(True)

    def prepareForDragOperation_(self, sender):
        return self._mod(sender) is not None

    def performDragOperation_(self, sender):
        m = self._mod(sender)
        self.hover = None
        urls = sender.draggingPasteboard().readObjectsForClasses_options_(
            [NSURL], {"NSPasteboardURLReadingFileURLsOnlyKey": True}) or []
        paths = [str(u.path()) for u in urls]
        n = self.app.store.shelf_add(paths, m) if (self.app and m) else 0
        log(f"taşıma alanına eklendi: {n} öğe ({m})")
        self.app.shelf_refresh()
        return n > 0

    # ---- tıklama ve dışarı sürükleme
    @objc.python_method
    def _vur(self, pt):
        L = self.yerlesim()

        def ic(r):
            return (r.origin.x <= pt.x <= r.origin.x + r.size.width and
                    r.origin.y <= pt.y <= r.origin.y + r.size.height)
        if ic(L["kapat"]):
            return ("kapat", None)
        for x, row, xbtn in L["rows"]:
            if ic(xbtn):
                return ("cikar", x)
            if ic(row):
                return ("satir", x)
        for ad in ("vazgec", "tasi"):
            if ad in L and ic(L[ad]):
                return (ad, None)
        if ic(L["baslik"]):
            return ("baslik", None)
        return (None, None)

    def mouseDown_(self, event):
        self.basili = self._vur(self.convertPoint_fromView_(event.locationInWindow(), None))
        self.surukleniyor = False

    def mouseDragged_(self, event):
        if self.surukleniyor or not self.basili:
            return
        tur, x = self.basili
        if tur == "satir":
            secim = [x]
        elif tur == "baslik" and self.app.store.shelf:
            secim = list(self.app.store.shelf)
        else:
            return
        self.surukleniyor = True
        self.suruklenen = [s["id"] for s in secim]
        ws = NSWorkspace.sharedWorkspace()
        pt = self.convertPoint_fromView_(event.locationInWindow(), None)
        ditems = []
        for i, s in enumerate(secim):
            di = NSDraggingItem.alloc().initWithPasteboardWriter_(NSURL.fileURLWithPath_(s["path"]))
            di.setDraggingFrame_contents_(
                NSMakeRect(pt.x - 20 + i * 4, pt.y - 20 + i * 4, 40, 40),
                ws.iconForFile_(s["path"]))
            ditems.append(di)
        self.beginDraggingSessionWithItems_event_source_(ditems, event, self)

    def mouseUp_(self, event):
        if self.surukleniyor or not self.basili:
            return
        tur, x = self.basili
        self.basili = None
        app = self.app
        if tur == "kapat":
            app.shelf_hide(force=True)
        elif tur == "cikar":
            app.store.shelf_remove([x["id"]])
            app.shelf_refresh()
        elif tur == "vazgec":
            app.store.shelf_remove([s["id"] for s in app.store.shelf])
            app.shelf_refresh()
        elif tur == "tasi":
            app.shelf_move_dialog()

    # NSDraggingSource
    def draggingSession_sourceOperationMaskForDraggingContext_(self, session, context):
        modlar = {s["mode"] for s in self.app.store.shelf_get(self.suruklenen)}
        if modlar == {"kes"}:
            return OP_MOVE
        if modlar == {"kopya"}:
            return OP_COPY
        return OP_MOVE | OP_COPY

    def draggingSession_endedAtPoint_operation_(self, session, point, operation):
        self.surukleniyor = False
        self.basili = None
        if operation == 0:
            return
        bitti = self.app.store.shelf_get(self.suruklenen)
        kes_yollar = [s["path"] for s in bitti if s["mode"] == "kes"]
        self.app.store.shelf_remove([s["id"] for s in bitti])
        log(f"taşıma alanından bırakıldı: {len(bitti)} öğe, işlem={operation}")
        if kes_yollar:
            # Finder taşımayı sürükleme bittikten sonra yapar; birkaç saniye bekleyip kontrol et
            NSTimer.scheduledTimerWithTimeInterval_target_selector_userInfo_repeats_(
                4.0, self.app, "kesKontrol:", kes_yollar, False)
        self.app.shelf_refresh()


