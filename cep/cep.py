def renk_hex(h):
    h = h.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    return NSColor.colorWithSRGBRed_green_blue_alpha_(r / 255, g / 255, b / 255, 1.0)


def renk_kutusu(h, s=16):
    img = NSImage.alloc().initWithSize_(NSMakeSize(s, s))
    img.lockFocus()
    renk_hex(h).set()
    NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(
        NSMakeRect(1, 1, s - 2, s - 2), 4, 4).fill()
    NSColor.colorWithWhite_alpha_(0, 0.15).set()
    NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(
        NSMakeRect(1, 1, s - 2, s - 2), 4, 4).stroke()
    img.unlockFocus()
    return img


def kucuk_resim(path, w=28, h=18):
    src = NSImage.alloc().initWithContentsOfFile_(str(path))
    if src is None:
        return sembol("photo", 16)
    img = NSImage.alloc().initWithSize_(NSMakeSize(w, h))
    img.lockFocus()
    sw, sh = src.size().width, src.size().height
    olcek = max(w / max(sw, 1), h / max(sh, 1))
    dw, dh = sw * olcek, sh * olcek
    NSBezierPath.bezierPathWithRoundedRect_xRadius_yRadius_(
        NSMakeRect(0, 0, w, h), 3, 3).addClip()
    src.drawInRect_fromRect_operation_fraction_(
        NSMakeRect((w - dw) / 2, (h - dh) / 2, dw, dh),
        NSMakeRect(0, 0, sw, sh), 2, 1.0)
    img.unlockFocus()
    return img


def yazi(s, boyut=13, agirlik=0.0, renk=None, kes=True, hiza=0):
    ps = NSMutableParagraphStyle.alloc().init()
    if kes:
        ps.setLineBreakMode_(4)  # sondan kes
    ps.setAlignment_(hiza)
    return NSAttributedString.alloc().initWithString_attributes_(s, {
        NSFontAttributeName: NSFont.systemFontOfSize_weight_(boyut, agirlik),
        NSForegroundColorAttributeName: renk or NSColor.labelColor(),
        NSParagraphStyleAttributeName: ps,
    })


