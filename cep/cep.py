    @objc.python_method
    def _yakala(self):
        types = set(str(t) for t in (self.pb.types() or []))
        if types & GIZLI:
            return
        try:
            app = NSWorkspace.sharedWorkspace().frontmostApplication().localizedName() or ""
        except Exception:
            app = ""
        if T_FILEURL in types:
            urls = self.pb.readObjectsForClasses_options_(
                [NSURL], {"NSPasteboardURLReadingFileURLsOnlyKey": True}) or []
            if urls:
                self.store.add_files([str(u.path()) for u in urls], app)
                return
        if (T_PNG in types or T_TIFF in types) and T_STRING not in types:
            data = self.pb.dataForType_(T_PNG) or self.pb.dataForType_(T_TIFF)
            if data:
                rep = NSBitmapImageRep.imageRepWithData_(data)
                if rep is not None:
                    png = bytes(rep.representationUsingType_properties_(4, {}))
                    item = self.store.add_image(png, int(rep.pixelsWide()),
                                                int(rep.pixelsHigh()), app)
                    if item and self.ayar.get("ocr", True) and "ocr" not in item:
                        self._ocr_baslat(item["id"], png, app)
                    return
        s = self.pb.stringForType_(T_STRING)
        if s:
            self.store.add_text(str(s), app)

    @objc.python_method
    def _panoya_yaz(self, item):
        pb = self.pb
        pb.clearContents()
        k = item["kind"]
        if k == "gorsel":
            img = NSImage.alloc().initWithContentsOfFile_(str(self.store.img_dir / item["image"]))
            if img is not None:
                pb.writeObjects_([img])
        elif k == "dosya":
            pb.writeObjects_([NSURL.fileURLWithPath_(p) for p in item["paths"]])
        else:
            pb.setString_forType_(item["text"], T_STRING)
        self.own_cc = pb.changeCount()
        self.last_cc = self.own_cc
        self.store.mark_used(item["id"])

