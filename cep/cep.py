    # ---- taşıma alanı paneli
    @objc.python_method
    def _shelf_kur(self):
        panel = NSPanel.alloc().initWithContentRect_styleMask_backing_defer_(
            NSMakeRect(0, 0, SHELF_W, 300), (1 << 7), 2, False)  # borderless + nonactivating
        panel.setLevel_(3)                 # yüzen pencere
        panel.setOpaque_(False)
        panel.setBackgroundColor_(NSColor.clearColor())
        panel.setHasShadow_(True)
        panel.setHidesOnDeactivate_(False)
        panel.setMovableByWindowBackground_(False)
        panel.setCollectionBehavior_(1 | 256)  # tüm masaüstleri + tam ekran
        fx = NSVisualEffectView.alloc().initWithFrame_(NSMakeRect(0, 0, SHELF_W, 300))
        fx.setMaterial_(5)
        fx.setBlendingMode_(0)
        fx.setState_(1)
        fx.setWantsLayer_(True)
        fx.layer().setCornerRadius_(16)
        fx.layer().setMasksToBounds_(True)
        fx.setAutoresizingMask_(2 | 16)
        view = ShelfView.alloc().initWithFrame_(NSMakeRect(0, 0, SHELF_W, 300))
        view.app = self
        view.setAutoresizingMask_(2 | 16)
        fx.addSubview_(view)
        panel.setContentView_(fx)
        self.shelf_panel, self.shelf_view = panel, view

    @objc.python_method
    def _dis_kenar_mi(self, scr):
        """Sağ kenarı başka bir monitöre bitişik değilse True."""
        f = scr.frame()
        sag = f.origin.x + f.size.width
        for o in NSScreen.screens():
            if o is scr:
                continue
            g = o.frame()
            bitisik = abs(g.origin.x - sag) < 2
            dikey = g.origin.y < f.origin.y + f.size.height and f.origin.y < g.origin.y + g.size.height
            if bitisik and dikey:
                return False
        return True

    @objc.python_method
    def _kenarlari_kur(self):
        for w in self.edges:
            w.orderOut_(None)
        self.edges = []
        W = 4
        for scr in NSScreen.screens():
            if not self._dis_kenar_mi(scr):
                continue
            f = scr.frame()
            h = f.size.height - 120
            w = NSWindow.alloc().initWithContentRect_styleMask_backing_defer_(
                NSMakeRect(f.origin.x + f.size.width - W, f.origin.y + 60, W, h), 0, 2, False)
            w.setReleasedWhenClosed_(False)
            w.setLevel_(3)
            w.setOpaque_(False)
            # Tamamen saydam pencereler sürüklemeleri alttakine geçirir; çok az görünürlük şart
            w.setBackgroundColor_(NSColor.colorWithWhite_alpha_(0.0, 0.02))
            w.setIgnoresMouseEvents_(False)
            w.setHasShadow_(False)
            w.setCollectionBehavior_(1 | 256 | 16)
            v = EdgeView.alloc().initWithFrame_(NSMakeRect(0, 0, W, h))
            v.app = self
            w.setContentView_(v)
            w.orderFrontRegardless()
            self.edges.append(w)
        log(f"kenar şeridi: {len(self.edges)} ekran ({len(NSScreen.screens())} monitör)")

    def applicationDidChangeScreenParameters_(self, note):
        try:
            self._kenarlari_kur()
        except Exception as e:
            log(f"kenar şeridi yenilenemedi: {e}")

    @objc.python_method
    def _ekran(self):
        m = NSEvent.mouseLocation()
        for scr in NSScreen.screens():
            f = scr.frame()
            if f.origin.x <= m.x <= f.origin.x + f.size.width and \
               f.origin.y <= m.y <= f.origin.y + f.size.height:
                return scr, m
        return NSScreen.mainScreen(), m

    @objc.python_method
    def shelf_refresh(self):
        if not self.shelf_panel:
            return
        h = self.shelf_view.yerlesim()["h"]
        fr = self.shelf_panel.frame()
        if abs(fr.size.height - h) > 0.5:
            top = fr.origin.y + fr.size.height
            self.shelf_panel.setFrame_display_(
                NSMakeRect(fr.origin.x, top - h, SHELF_W, h), True)
        self.shelf_view.setNeedsDisplay_(True)
        self.shelf_touched()
        if getattr(self, "panel", None) is not None and self.panel.acik():
            self.panel.yenile()

    @objc.python_method
    def shelf_touched(self):
        self.shelf_last_touch = time.time()

    @objc.python_method
    def shelf_show(self, pin=False, konum="ikon"):
        if pin:
            self.shelf_pinned_open = True
        if self.shelf_panel.isVisible():
            self.shelf_touched()
            return
        self.store.shelf_cleanup()
        scr, m = self._ekran()
        vf = scr.visibleFrame()
        f = scr.frame()
        h = self.shelf_view.yerlesim()["h"]
        if konum == "ikon":
            cx = m.x
            ust_bolgede = m.y >= f.origin.y + f.size.height - 40
            if not ust_bolgede:
                # fare menü çubuğunda değilse (ör. açılışta) ikonun konumunu kullan
                try:
                    bf = self.status.button().window().frame()
                    cx = bf.origin.x + bf.size.width / 2
                    bscr = self.status.button().window().screen()
                    if bscr is not None:
                        vf = bscr.visibleFrame()
                except Exception:
                    pass
            x = cx - SHELF_W / 2
            x = max(vf.origin.x + 8, min(x, vf.origin.x + vf.size.width - SHELF_W - 8))
            y = vf.origin.y + vf.size.height - h - 6
        else:
            y = min(max(m.y - h / 2, vf.origin.y + 20), vf.origin.y + vf.size.height - h - 20)
            x = vf.origin.x + vf.size.width - SHELF_W
        self.shelf_panel.setFrame_display_(NSMakeRect(x, y, SHELF_W, h), True)
        self.shelf_panel.orderFrontRegardless()
        self.shelf_view.setNeedsDisplay_(True)
        self.shelf_touched()

    @objc.python_method
    def shelf_hide(self, force=False):
        if force:
            self.shelf_pinned_open = False
        self.shelf_panel.orderOut_(None)

    @objc.python_method
    def _shelf_otomatik_gizle(self):
        p = self.shelf_panel
        if not p or not p.isVisible() or self.store.shelf or self.shelf_pinned_open:
            return
        m = NSEvent.mouseLocation()
        f = p.frame()
        icinde = (f.origin.x - 30 <= m.x <= f.origin.x + f.size.width + 30 and
                  f.origin.y - 30 <= m.y <= f.origin.y + f.size.height + 30)
        if not icinde and time.time() - self.shelf_last_touch > 1.2:
            self.shelf_hide()

    @objc.python_method
    def shelf_move_dialog(self):
        if not self.store.shelf:
            return
        NSApplication.sharedApplication().activateIgnoringOtherApps_(True)
        op = NSOpenPanel.openPanel()
        op.setCanChooseDirectories_(True)
        op.setCanChooseFiles_(False)
        op.setCanCreateDirectories_(True)
        op.setPrompt_(t("Buraya taşı"))
        op.setMessage_(t("Taşıma alanındaki dosyalar bu klasöre taşınacak "
                         "(kopyalanacak olarak işaretlenenler kopyalanır)."))
        if op.runModal() != 1:
            return
        hedef = str(op.URL().path())
        sonuc = self.store.shelf_move_to([s["id"] for s in self.store.shelf], hedef)
        hatalar = [(x, d) for x, _, d in sonuc if d not in ("tamam", "zaten orada")]
        log(f"'{hedef}' klasörüne: {len(sonuc) - len(hatalar)} tamam, {len(hatalar)} hata")
        if hatalar:
            self._uyari(t("Bazı dosyalar taşınamadı:") + "\n" + "\n".join(
                f"• {os.path.basename(x['path'])}: {d}" for x, d in hatalar))
        self.shelf_refresh()


